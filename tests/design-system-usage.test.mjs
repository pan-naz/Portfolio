import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildSystemInventory } from '../src/data/system-inventory.ts';
import { dsComponents } from '../src/data/ds-components.ts';
import { validateInventoryCoverage } from '../scripts/validate-design-system.mjs';
const model = buildSystemInventory();
const components = dsComponents.map(item => item.file);
const tokens = model.tokens.map(token => token.name);
const icons = model.iconNames;
const css = readFileSync('src/styles/tokens.css', 'utf8');
const catalog = readFileSync('src/components/DSCatalog.astro', 'utf8');
const check = (c = components, t = tokens, i = icons, source = css) => validateInventoryCoverage(model, c, t, i, source, catalog);
assert.deepEqual(check(), []);
assert.ok(check(components.slice(1)).some(error => error.includes('Undocumented website component')));
assert.ok(check(components, tokens.slice(1)).some(error => error.includes('Undocumented website token')));
assert.ok(check(components, tokens, icons.slice(1)).some(error => error.includes('Undocumented website icon')));
assert.ok(check([...components, 'src/components/CatalogOnly.astro']).some(error => error.includes('Catalog-only component')));
assert.ok(check(components, [...tokens, 'catalog-only']).some(error => error.includes('Catalog-only token')));
assert.ok(check(components, tokens, [...icons, 'catalog-only']).some(error => error.includes('Catalog-only icon')));
assert.ok(check(components, tokens, icons, css + `\n--${model.privateNames[0]}: #123456;`).some(error => error.includes('Project-only value')));
assert.ok(check(components, tokens, icons, css + `\n--font-body: '${model.projectFonts[0]}';`).some(error => error.includes('Project-only font')));
for (const token of model.tokens) assert.ok(token.resolvedLight && token.resolvedDark, `${token.name} resolves in both themes`);
console.log('Design-system usage guard rejects missing/unused entries and project-only tokens/fonts.');
