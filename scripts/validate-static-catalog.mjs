import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const read = path => readFileSync(resolve(root, path), 'utf8');
const home = read('dist/index.html');
const catalog = read('dist/design-system/index.html');
const preview = read('dist/design-system/preview/index.html');
const body = html => html.match(/<body[^>]*>([\s\S]*?)<\/body>/)[1].replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '').replace(/\s+/g, ' ').trim();
assert.equal(body(home), body(preview), 'Website and static preview must render identical shared composition');
assert.ok(!/<script\b/.test(preview), 'Static preview must contain no scripts');
assert.ok(/data-static/.test(preview) && /data-static/.test(catalog), 'DS surfaces opt into static styles');
assert.ok(!/data-static/.test(home), 'Website must not enter static mode');
const styles = html => [...html.matchAll(/<link[^>]*href="([^"]+\.css)"[^>]*>/g)].map(([,path]) => read('dist' + path)).concat([...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(([,css]) => css)).join('\n');
assert.ok(styles(preview).includes('html[data-static]'), 'Preview must load motion suppression');
assert.ok(styles(catalog).includes('html[data-static]'), 'Catalog must load motion suppression');
assert.ok(!styles(home).includes('html[data-static]'), 'Catalog motion CSS must not enter the website bundle');
assert.ok(catalog.includes('sandbox="allow-same-origin"'), 'Embedded preview blocks script execution');
assert.ok(!catalog.includes('role="tablist"') && !catalog.includes('id="ds-search"'), 'Retired tab and search interfaces must stay removed');
const ids = [...catalog.matchAll(/\bid="([^"]+)"/g)].map(([,id]) => id);
assert.equal(new Set(ids).size, ids.length, 'Catalog IDs must remain unique');
console.log('Static catalog verified: identical shared page, no preview scripts, isolated motion CSS, sandboxed embed and unique IDs.');
